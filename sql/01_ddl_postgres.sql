-- Erros do DDL original (sql/01_ddl_enunciado.sql) corrigidos aqui:
--  1. entradas_mercadoria: a PK usava ordem_compra, mas a coluna não existia.
--  2. produtos_filial: faltava a vírgula antes do CONSTRAINT (erro de sintaxe).
--  3. produtos_filial: a PK usava "idproduto", mas a coluna se chama produto_id.
--  4. produtos_filial: "decricao" (typo) -> descricao; "idfonecedor" (typo) -> idfornecedor.
--  5. fornecedor: "idforncedor" (typo) -> idfornecedor; a PK citava "idproduto",
--     que não existe na tabela (e fornecedor não tem produto).
--  6. Tipos incoerentes entre tabelas: fornecedor.idfornecedor era varchar, mas
--     produtos_filial.idfornecedor e pedido_compra.fornecedor_id eram int4.
--     Agora o código do fornecedor é numérico (int) nas três tabelas.
--  7. Colunas de identificação (pedido_id, item, ordem_compra) como float8, inclusive
--     dentro de PK. Trocadas por inteiros. Dinheiro e quantidades (float8) viraram
--     numeric, para não acumular erro de arredondamento.
--  8. venda: a PK se chamava pk_consumo (nome de outra tabela) -> pk_venda;
--     horariomov era varchar(8) -> time; produto_id tinha DEFAULT '' (vazio) e
--     qtde_vendida podia ser NULL.
--  9. filial_id tinha tipos diferentes (int8 em venda, int4 nas demais) -> int.
-- 10. pedido_compra: fornecedor_id com DEFAULT 0 (fornecedor 0 não existe) e
--     qtde_pendente digitável à mão (podia divergir de pedida - entregue)
--     -> coluna calculada.
-- 11. Colunas que fazem parte de PK tinham DEFAULT 0 / '0' (permitia gravar chave
--     "zerada" sem perceber). Os defaults foram removidos das colunas de PK.
-- 12. Nenhuma tabela tinha chave estrangeira -> criadas as que os dados permitem.
--     Não há FK de venda para produtos_filial nem de entradas para pedido_compra
--     de propósito: os dados do cliente violam essas relações (ver
--     sql/04_validacao.sql) e queremos importá-los para poder mostrar o erro.
-- =====================================================================

DROP TABLE IF EXISTS public.venda CASCADE;
DROP TABLE IF EXISTS public.entradas_mercadoria CASCADE;
DROP TABLE IF EXISTS public.pedido_compra CASCADE;
DROP TABLE IF EXISTS public.produtos_filial CASCADE;
DROP TABLE IF EXISTS public.fornecedor CASCADE;

CREATE TABLE public.fornecedor (
    idfornecedor  int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    razao_social  varchar(255) NOT NULL,
    CONSTRAINT fornecedor_pkey PRIMARY KEY (idfornecedor)
);

CREATE TABLE public.produtos_filial (
    filial_id       int            NOT NULL,
    produto_id      varchar(25)    NOT NULL,
    descricao       varchar(255)   NOT NULL,
    estoque         numeric(14, 4) NOT NULL DEFAULT 0,
    preco_unitario  numeric(12, 4) NOT NULL DEFAULT 0,
    preco_compra    numeric(12, 4) NOT NULL DEFAULT 0,
    preco_venda     numeric(12, 4) NOT NULL DEFAULT 0,
    idfornecedor    int            NULL,
    CONSTRAINT produtos_filial_pkey PRIMARY KEY (filial_id, produto_id),
    CONSTRAINT fk_produtos_filial_fornecedor
        FOREIGN KEY (idfornecedor) REFERENCES public.fornecedor (idfornecedor)
);

CREATE TABLE public.pedido_compra (
    pedido_id          bigint         NOT NULL,
    data_pedido        date           NOT NULL,
    item               int            NOT NULL,
    produto_id         varchar(25)    NOT NULL,
    descricao_produto  varchar(255)   NULL,
    ordem_compra       bigint         NOT NULL DEFAULT 0,   -- 0 = pedido sem ordem de compra
    qtde_pedida        numeric(14, 4) NOT NULL,
    filial_id          int            NOT NULL,
    data_entrega       date           NULL,
    qtde_entregue      numeric(14, 4) NOT NULL DEFAULT 0,
    qtde_pendente      numeric(14, 4) GENERATED ALWAYS AS (qtde_pedida - qtde_entregue) STORED,
    preco_compra       numeric(12, 4) NOT NULL DEFAULT 0,
    fornecedor_id      int            NULL,
    CONSTRAINT pedido_compra_pkey PRIMARY KEY (pedido_id, produto_id, item),
    CONSTRAINT fk_pedido_compra_fornecedor
        FOREIGN KEY (fornecedor_id) REFERENCES public.fornecedor (idfornecedor),
    CONSTRAINT fk_pedido_compra_produto
        FOREIGN KEY (filial_id, produto_id) REFERENCES public.produtos_filial (filial_id, produto_id)
);

CREATE TABLE public.entradas_mercadoria (
    data_entrada       date           NOT NULL,
    nro_nfe            varchar(255)   NOT NULL,
    item               int            NOT NULL,
    produto_id         varchar(25)    NOT NULL,
    descricao_produto  varchar(255)   NULL,
    ordem_compra       bigint         NOT NULL,             -- coluna que faltava no DDL original
    qtde_recebida      numeric(14, 4) NOT NULL,
    filial_id          int            NOT NULL,
    custo_unitario     numeric(12, 4) NOT NULL DEFAULT 0,
    CONSTRAINT entradas_mercadoria_pkey PRIMARY KEY (ordem_compra, item, produto_id, nro_nfe),
    CONSTRAINT fk_entradas_produto
        FOREIGN KEY (filial_id, produto_id) REFERENCES public.produtos_filial (filial_id, produto_id)
);

CREATE TABLE public.venda (
    venda_id        bigint         NOT NULL,
    data_emissao    date           NOT NULL,
    horariomov      time           NOT NULL DEFAULT '00:00:00',
    produto_id      varchar(25)    NOT NULL,
    qtde_vendida    numeric(14, 4) NOT NULL,
    valor_unitario  numeric(12, 4) NOT NULL DEFAULT 0,
    filial_id       int            NOT NULL DEFAULT 1,
    item            int            NOT NULL DEFAULT 0,
    unidade_medida  varchar(3)     NULL,
    CONSTRAINT pk_venda PRIMARY KEY (filial_id, venda_id, data_emissao, produto_id, item, horariomov)
);

-- Índices de apoio às consultas das Partes 2, 3 e 4
CREATE INDEX idx_venda_data         ON public.venda (data_emissao);
CREATE INDEX idx_pedido_ordem       ON public.pedido_compra (ordem_compra);
CREATE INDEX idx_entradas_ordem     ON public.entradas_mercadoria (ordem_compra);
