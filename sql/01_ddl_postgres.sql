BEGIN;

CREATE TABLE public.fornecedor (
    idfornecedor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_origem VARCHAR(25) UNIQUE,
    razao_social VARCHAR(255) NOT NULL
);

CREATE TABLE public.produtos_filial (
    filial_id BIGINT NOT NULL,
    produto_id VARCHAR(25) NOT NULL,
    descricao VARCHAR(255) NOT NULL,
    estoque NUMERIC(18, 6) DEFAULT 0,
    preco_unitario NUMERIC(18, 4) DEFAULT 0,
    preco_compra NUMERIC(18, 4) DEFAULT 0,
    preco_venda NUMERIC(18, 4) DEFAULT 0,
    idfornecedor BIGINT REFERENCES public.fornecedor (idfornecedor),
    PRIMARY KEY (filial_id, produto_id)
);

CREATE TABLE public.pedido_compra (
    pedido_id BIGINT NOT NULL,
    data_pedido DATE,
    item INTEGER NOT NULL,
    produto_id VARCHAR(25) NOT NULL,
    descricao_produto VARCHAR(255),
    ordem_compra BIGINT NOT NULL,
    qtde_pedida NUMERIC(18, 6),
    filial_id BIGINT,
    data_entrega DATE,
    qtde_entregue NUMERIC(18, 6) DEFAULT 0 NOT NULL,
    qtde_pendente NUMERIC(18, 6),
    preco_compra NUMERIC(18, 4),
    fornecedor_id BIGINT REFERENCES public.fornecedor (idfornecedor),
    PRIMARY KEY (pedido_id, produto_id, item)
);

CREATE TABLE public.entradas_mercadoria (
    data_entrada DATE,
    nro_nfe VARCHAR(255) NOT NULL,
    item INTEGER NOT NULL,
    produto_id VARCHAR(25) NOT NULL,
    descricao_produto VARCHAR(255),
    ordem_compra BIGINT NOT NULL,
    qtde_recebida NUMERIC(18, 6),
    filial_id BIGINT,
    custo_unitario NUMERIC(18, 4),
    PRIMARY KEY (ordem_compra, item, produto_id, nro_nfe)
);

CREATE TABLE public.venda (
    venda_id BIGINT NOT NULL,
    data_emissao DATE NOT NULL,
    horariomov TIME NOT NULL,
    produto_id VARCHAR(25) NOT NULL,
    qtde_vendida NUMERIC(18, 6),
    valor_unitario NUMERIC(18, 4),
    filial_id BIGINT NOT NULL,
    item INTEGER NOT NULL,
    unidade_medida VARCHAR(3),
    PRIMARY KEY (filial_id, venda_id, data_emissao, produto_id, item, horariomov)
);

-- Uma linha por registro não vazio da planilha na última carga concluída.
CREATE TABLE public.importacao_linhas (
    aba VARCHAR(30) NOT NULL,
    linha_excel INTEGER NOT NULL,
    status VARCHAR(10) NOT NULL CHECK (status IN ('inserida', 'existente', 'rejeitada')),
    ocorrencias JSONB NOT NULL,
    dados_origem JSONB NOT NULL,
    PRIMARY KEY (aba, linha_excel)
);

COMMIT;
