DROP TABLE IF EXISTS public.venda CASCADE;
DROP TABLE IF EXISTS public.entradas_mercadoria CASCADE;
DROP TABLE IF EXISTS public.pedido_compra CASCADE;
DROP TABLE IF EXISTS public.produtos_filial CASCADE;
DROP TABLE IF EXISTS public.fornecedor CASCADE;

CREATE TABLE public.fornecedor (
    idfornecedor integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_origem varchar(25) UNIQUE,
    razao_social varchar(255) NOT NULL
);

CREATE TABLE public.produtos_filial (
    filial_id integer NOT NULL,
    produto_id varchar(25) NOT NULL,
    descricao varchar(255) NOT NULL,
    estoque numeric(12, 3) NOT NULL DEFAULT 0 CHECK (estoque >= 0),
    preco_unitario numeric(12, 4) NOT NULL DEFAULT 0 CHECK (preco_unitario >= 0),
    preco_compra numeric(12, 4) NOT NULL DEFAULT 0 CHECK (preco_compra >= 0),
    preco_venda numeric(12, 4) NOT NULL DEFAULT 0 CHECK (preco_venda >= 0),
    idfornecedor integer NULL,
    CONSTRAINT produtos_filial_pkey PRIMARY KEY (filial_id, produto_id),
    CONSTRAINT fk_produtos_fornecedor FOREIGN KEY (idfornecedor)
        REFERENCES public.fornecedor (idfornecedor)
);

CREATE TABLE public.pedido_compra (
    pedido_id bigint NOT NULL,
    data_pedido date NULL,
    item integer NOT NULL DEFAULT 0,
    produto_id varchar(25) NOT NULL DEFAULT '0',
    descricao_produto varchar(255) NULL,
    ordem_compra bigint NOT NULL DEFAULT 0,
    qtde_pedida numeric(12, 3) NULL CHECK (qtde_pedida >= 0),
    filial_id integer NULL,
    data_entrega date NULL,
    qtde_entregue numeric(12, 3) NOT NULL DEFAULT 0 CHECK (qtde_entregue >= 0),
    qtde_pendente numeric(12, 3) GENERATED ALWAYS AS (COALESCE(qtde_pedida, 0) - qtde_entregue) STORED,
    preco_compra numeric(12, 4) NOT NULL DEFAULT 0 CHECK (preco_compra >= 0),
    fornecedor_id integer NULL,
    CONSTRAINT pedido_compra_pkey PRIMARY KEY (pedido_id, produto_id, item),
    CONSTRAINT fk_pedido_fornecedor FOREIGN KEY (fornecedor_id)
        REFERENCES public.fornecedor (idfornecedor)
);

CREATE TABLE public.entradas_mercadoria (
    data_entrada date NULL,
    nro_nfe varchar(255) NOT NULL,
    item integer NOT NULL DEFAULT 0,
    ordem_compra bigint NOT NULL DEFAULT 0,
    produto_id varchar(25) NOT NULL DEFAULT '0',
    descricao_produto varchar(255) NULL,
    qtde_recebida numeric(12, 3) NULL CHECK (qtde_recebida >= 0),
    filial_id integer NULL,
    custo_unitario numeric(12, 4) NOT NULL DEFAULT 0 CHECK (custo_unitario >= 0),
    CONSTRAINT entradas_mercadoria_pkey PRIMARY KEY (ordem_compra, item, produto_id, nro_nfe)
);

CREATE TABLE public.venda (
    venda_id bigint NOT NULL,
    data_emissao date NOT NULL,
    horariomov time NOT NULL DEFAULT '00:00:00',
    produto_id varchar(25) NOT NULL,
    qtde_vendida numeric(12, 3) NOT NULL CHECK (qtde_vendida > 0),
    valor_unitario numeric(12, 4) NOT NULL DEFAULT 0 CHECK (valor_unitario >= 0),
    filial_id integer NOT NULL DEFAULT 1,
    item integer NOT NULL DEFAULT 1,
    unidade_medida varchar(3) NULL,
    CONSTRAINT pk_venda PRIMARY KEY (filial_id, venda_id, data_emissao, produto_id, item, horariomov)
);